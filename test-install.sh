# test-install.sh: test install.sh in every mode, without touching your desktop.
#
# Usage:
#   ./dist.sh
#   ./test-install.sh
#
# What it does:
#   - runs install.sh with a throwaway HOME for every case
#   - puts a stub xfconf-query first on PATH, which only records its arguments
#   - downloads from the local dist/ archive (file://), never the network
#   - removes its work folder when it ends
#
# Cases:
#   - repo with build/: installs every theme
#   - repo without build/: stops, installs nothing
#   - script on its own: downloads, installs every theme, leaves no temp folder
#   - script on its own, bad URL: fails, installs nothing, leaves no temp folder
#   - theme name: switches xfwm4 through xfconf-query
#   - same-named folder that is not a Beacon theme: refused, left untouched
#   - --uninstall: removes Beacon themes only
#
# Needs:
#   - build/ and dist/xfce4-beacon-theme.tar.gz (./dist.sh makes both)
#   - curl, tar
set -euo pipefail

ROOT=$(CDPATH='' cd -- "$(dirname -- "$0")" && pwd)
NAME=xfce4-beacon-theme
MARK='generated by xfce4-beacon-theme build.sh'
ARCHIVE=$ROOT/dist/$NAME.tar.gz

die() {
	echo "test-install.sh: $*" >&2
	exit 1
}

[ -d "$ROOT/build" ] || die "no build/; run ./dist.sh first"
[ -f "$ARCHIVE" ] || die "no $ARCHIVE; run ./dist.sh first"

WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT

# stub xfconf-query: records each call's arguments in $WORK/xfconf.log
mkdir -p "$WORK/bin"
printf '#!/bin/sh\necho "$*" >>"%s/xfconf.log"\n' "$WORK" >"$WORK/bin/xfconf-query"
chmod +x "$WORK/bin/xfconf-query"

# the themes build/ holds, and the first one, for the switch case
themes=()
for d in "$ROOT"/build/*/; do
	[ -f "$d/xfwm4/themerc" ] && themes+=("$(basename "$d")")
done
[ ${#themes[@]} -gt 0 ] || die "build/ holds no themes"
want=${#themes[@]}
first=${themes[0]}

fails=0 n=0
ok() { echo "ok:   $1"; }
bad() {
	echo "FAIL: $1"
	sed 's/^/      /' "$WORK/out"
	fails=$((fails + 1))
}

# fresh: a new empty HOME and TMPDIR for the next case
fresh() {
	n=$((n + 1))
	H=$WORK/home$n
	T=$WORK/tmp$n
	mkdir -p "$H" "$T"
	: >"$WORK/xfconf.log"
}

# run <install.sh> [args...]: run it in the current case's HOME; output in $WORK/out
run() {
	HOME=$H TMPDIR=$T PATH=$WORK/bin:$PATH "$@" >"$WORK/out" 2>&1
}

# installed: how many Beacon themes the current HOME holds
installed() {
	local c=0 d
	for d in "$H"/.themes/*/; do
		if grep -qsF "$MARK" "$d/xfwm4/themerc"; then c=$((c + 1)); fi
	done
	echo "$c"
}

# empty <dir>: <dir> holds nothing
empty() { [ -z "$(ls -A "$1")" ]; }

# --- repo with build/ -----------------------------------------------------------
fresh
if run "$ROOT/install.sh" && [ "$(installed)" = "$want" ]; then
	ok "repo with build/ installs all $want themes"
else
	bad "repo with build/ installs all $want themes"
fi

# --- repo without build/ --------------------------------------------------------
fresh
mkdir -p "$WORK/repo"
cp "$ROOT/install.sh" "$ROOT/build.sh" "$WORK/repo/"
if ! run "$WORK/repo/install.sh" && grep -qF 'run ./build.sh' "$WORK/out" && [ ! -e "$H/.themes" ]; then
	ok "repo without build/ stops and installs nothing"
else
	bad "repo without build/ stops and installs nothing"
fi

# --- script on its own ----------------------------------------------------------
fresh
mkdir -p "$WORK/alone"
cp "$ROOT/install.sh" "$WORK/alone/"
if BEACON_URL=file://$ARCHIVE run "$WORK/alone/install.sh" && [ "$(installed)" = "$want" ] && empty "$T"; then
	ok "script on its own downloads and installs all $want themes, no temp folder left"
else
	bad "script on its own downloads and installs all $want themes, no temp folder left"
fi

# --- script on its own, bad URL -------------------------------------------------
fresh
if ! BEACON_URL=file://$WORK/missing.tar.gz run "$WORK/alone/install.sh" && [ ! -e "$H/.themes" ] && empty "$T"; then
	ok "bad URL fails, installs nothing, no temp folder left"
else
	bad "bad URL fails, installs nothing, no temp folder left"
fi

# --- theme name switches xfwm4 --------------------------------------------------
fresh
if run "$ROOT/install.sh" "$first" && grep -qxF -- "-c xfwm4 -p /general/theme -s $first" "$WORK/xfconf.log"; then
	ok "theme name switches xfwm4 to $first"
else
	bad "theme name switches xfwm4 to $first"
fi

# --- same-named folder that is not a Beacon theme -------------------------------
fresh
mkdir -p "$H/.themes/$first"
echo keep >"$H/.themes/$first/mine"
if ! run "$ROOT/install.sh" && [ "$(cat "$H/.themes/$first/mine")" = keep ] && [ "$(installed)" = 0 ]; then
	ok "a non-Beacon folder named $first is refused and left untouched"
else
	bad "a non-Beacon folder named $first is refused and left untouched"
fi

# --- --uninstall ----------------------------------------------------------------
fresh
mkdir -p "$H/.themes/Other/xfwm4"
echo 'not ours' >"$H/.themes/Other/xfwm4/themerc"
if run "$ROOT/install.sh" && run "$ROOT/install.sh" --uninstall && [ "$(installed)" = 0 ] && [ -f "$H/.themes/Other/xfwm4/themerc" ]; then
	ok "--uninstall removes Beacon themes only"
else
	bad "--uninstall removes Beacon themes only"
fi

[ "$fails" = 0 ] || die "$fails case(s) failed"
echo "test-install.sh: all $n cases passed"
