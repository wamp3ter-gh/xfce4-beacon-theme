# install.sh: install the Beacon xfwm4 themes into ~/.themes.
#
# Usage:
#   ./install.sh [--clean] [theme]
#   ./install.sh --uninstall
#
# Arguments:
#   - theme: also switch xfwm4 to this theme
#   - --clean: also remove Beacon themes in ~/.themes that are no longer being installed
#   - --uninstall: remove every Beacon theme from ~/.themes, and install nothing
#
# Where the themes come from:
#   - build/ next to this script: install from it (a repository after ./build.sh,
#     or an unpacked release)
#   - a repository without build/: stop; run ./build.sh beacon.conf first
#   - this script on its own: download the latest release and install from it
#   - it never builds
#
# Environment:
#   - BEACON_URL: the release archive to download
#     (default: the latest release on GitLab)
#
# Safety:
#   - a theme folder that build.sh did not make is never removed or overwritten
#   - every check runs before anything changes
#   - each theme is copied beside the old one, then swapped in
#   - so a failed copy leaves the old theme in place
#   - a download goes to a temporary folder, removed however the run ends
#
# Needs:
#   - xfconf-query (Xfce), only when switching to a theme
#   - curl and tar, only when downloading
set -euo pipefail

ROOT=$(CDPATH='' cd -- "$(dirname -- "$0")" && pwd)
NAME=xfce4-beacon-theme
URL=${BEACON_URL:-https://gitlab.com/wamp3ter/$NAME/-/releases/permalink/latest/downloads/$NAME.tar.gz}
MARK='generated by xfce4-beacon-theme build.sh'
DEST=$HOME/.themes

die() {
	echo "install.sh: $*" >&2
	exit 1
}
# ours <dir>: the theme in <dir> came from this repo's build.sh
ours() { grep -qsF "$MARK" "$1/xfwm4/themerc"; }

clean=0 uninstall=0 theme=""
for a in "$@"; do
	case $a in
	--clean) clean=1 ;;
	--uninstall) uninstall=1 ;;
	-*) die "unknown option '$a' (usage: ./install.sh [--clean] [theme] | --uninstall)" ;;
	*)
		[ -z "$theme" ] || die "give one theme name, not '$theme' and '$a'"
		theme=$a
		;;
	esac
done

if [ "$uninstall" = 1 ]; then
	[ "$clean" = 0 ] && [ -z "$theme" ] || die "--uninstall takes no other arguments"
	removed=0
	for d in "$DEST"/*/; do
		d=${d%/}
		if ours "$d"; then
			rm -r "$d"
			echo "removed $d"
			removed=$((removed + 1))
		fi
	done
	echo "$removed Beacon theme(s) removed; switch to another theme in Settings > Window Manager if one was in use"
	exit 0
fi

# --- source: the build/ folder to install from ---------------------------------
TMP=""
cleanup() { if [ -n "$TMP" ]; then rm -rf "$TMP"; fi; }
trap cleanup EXIT
if [ -d "$ROOT/build" ]; then
	SRC=$ROOT/build
elif [ -f "$ROOT/build.sh" ]; then
	die "no build/; run ./build.sh beacon.conf first"
else
	missing=()
	for c in curl tar; do command -v "$c" >/dev/null || missing+=("$c"); done
	[ ${#missing[@]} -eq 0 ] || die "missing tools: ${missing[*]} (needed to download the release)"
	TMP=$(mktemp -d)
	echo "downloading $URL"
	curl -fsSL -o "$TMP/release.tar.gz" "$URL" || die "could not download $URL"
	tar -xzf "$TMP/release.tar.gz" -C "$TMP" || die "could not unpack $URL"
	SRC=$TMP/$NAME/build
	[ -d "$SRC" ] || die "the archive from $URL has no $NAME/build/"
fi

# --- checks: nothing changes until all of these pass ---------------------------
built=()
for d in "$SRC"/*/; do
	[ -f "$d/xfwm4/themerc" ] && built+=("$(basename "$d")")
done
[ ${#built[@]} -gt 0 ] || die "$SRC holds no themes"

if [ -n "$theme" ]; then
	found=0
	for n in "${built[@]}"; do [ "$n" = "$theme" ] && found=1; done
	[ "$found" = 1 ] || die "no theme '$theme' to install (available: ${built[*]})"
	command -v xfconf-query >/dev/null ||
		die "missing tool: xfconf-query (part of Xfce); install without a theme name to only copy"
fi

clashes=()
for n in "${built[@]}"; do
	dest=$DEST/$n
	if [ -e "$dest" ] || [ -L "$dest" ]; then
		ours "$dest" || clashes+=("$dest")
	fi
done
[ ${#clashes[@]} -eq 0 ] || die "these exist and are not Beacon themes, so nothing was changed: ${clashes[*]}"

# --- changes ------------------------------------------------------------------
mkdir -p "$DEST"
if [ "$clean" = 1 ]; then
	for d in "$DEST"/*/; do
		d=${d%/}
		ours "$d" || continue
		keep=0
		for n in "${built[@]}"; do [ "$(basename "$d")" = "$n" ] && keep=1; done
		if [ "$keep" = 0 ]; then
			rm -r "$d"
			echo "removed $d"
		fi
	done
fi

for n in "${built[@]}"; do
	dest=$DEST/$n
	tmp=$DEST/.$n.beacon-new
	rm -rf "$tmp"
	cp -r "$SRC/$n" "$tmp"
	if [ -e "$dest" ] || [ -L "$dest" ]; then rm -r "$dest"; fi
	mv "$tmp" "$dest"
	echo "installed ~/.themes/$n"
done

if [ -n "$theme" ]; then
	xfconf-query -c xfwm4 -p /general/theme -s "$theme"
	echo "xfwm4 theme: $theme"
fi
